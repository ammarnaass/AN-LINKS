export async function seedPlatforms(prisma: PrismaClient): Promise<void> {
  console.log("🌐 Seeding Verified Supported Platforms (20 Platforms)...");

  for (const item of PLATFORMS_SEED_DATA) {
    await prisma.platform.upsert({
      where: { slug: item.slug },
      update: {
        nameAr: item.nameAr,
        nameEn: item.nameEn,
        category: item.category,
        defaultIcon: item.defaultIcon,
        brandColor: item.brandColor,
        domainPattern: item.domainPattern,
        urlPlaceholder: item.urlPlaceholder,
        isEnabled: item.isEnabled,
        isVerified: item.isVerified,
        sortOrder: item.sortOrder,
      },
      create: {
        slug: item.slug,
        nameAr: item.nameAr,
        nameEn: item.nameEn,
        category: item.category,
        defaultIcon: item.defaultIcon,
        brandColor: item.brandColor,
        domainPattern: item.domainPattern,
        urlPlaceholder: item.urlPlaceholder,
        isEnabled: item.isEnabled,
        isVerified: item.isVerified,
        sortOrder: item.sortOrder,
      },
    });
  }

  console.log(`✅ ${PLATFORMS_SEED_DATA.length} platforms seeded/updated successfully.`);
}
