const RESERVED_SET = new Set(RESERVED_USERNAMES.map((name) => name.toLowerCase()));

export function isUsernameReserved(username: string): boolean {
  if (!username || typeof username !== "string") return true;
  return RESERVED_SET.has(username.trim().toLowerCase());
}

